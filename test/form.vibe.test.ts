import { nextTick } from "@usevibejs/ui";
import { mount } from "@usevibejs/ui/testing";
import { expect, it } from "vitest";
import { focusField, focusFirstInvalid } from "../src/focus.ts";
import Shell from "./fixtures/Shell.vibe";
import VibecnFields from "./fixtures/VibecnFields.vibe";

it("binds native controls, nested fields and context inside components", async () => {
  const view = mount(Shell);
  const root = view.element;
  const email = root.querySelector<HTMLInputElement>("#email")!;
  email.value = "ada";
  email.dispatchEvent(new Event("input"));
  email.dispatchEvent(new Event("blur"));
  await nextTick();
  expect(email.getAttribute("aria-invalid")).toBe("true");
  expect(root.querySelector("#email-error")!.textContent).toBe("Enter an email");
  expect(focusFirstInvalid(root)).toBe(true);
  expect(focusFirstInvalid()).toBe(true);
  expect(document.activeElement).toBe(email);
  email.value = "ada@example.com";
  email.dispatchEvent(new Event("input"));
  await nextTick();
  const city = root.querySelector<HTMLInputElement>("#city")!;
  city.value = "Paris";
  city.dispatchEvent(new Event("input"));
  await nextTick();
  const agree = root.querySelector<HTMLInputElement>("#agree")!;
  agree.click();
  await nextTick();
  expect(root.querySelector("[data-agree]")!.textContent).toBe("true");
  const plan = root.querySelector<HTMLSelectElement>("#plan")!;
  plan.value = "team";
  plan.dispatchEvent(new Event("change"));
  await nextTick();
  expect(root.querySelector("[data-plan]")!.textContent).toBe("team");
  (root.querySelector("#toggle") as HTMLButtonElement).click();
  await nextTick();
  const nickname = root.querySelector<HTMLInputElement>("#nickname")!;
  nickname.value = "Ada";
  nickname.dispatchEvent(new Event("input"));
  (root.querySelector("#toggle") as HTMLButtonElement).click();
  await nextTick();
  expect(root.querySelector("#nickname")).toBeNull();
  (root.querySelector("#toggle") as HTMLButtonElement).click();
  await nextTick();
  expect(root.querySelector<HTMLInputElement>("#nickname")!.value).toBe("Ada");
  expect(root.querySelector("[data-seen]")!.textContent).toBe("7");
  expect(root.querySelector("[data-field]")!.textContent).toBe("plan");
  expect(root.querySelector("[data-field-error]")!.textContent).toMatch(/useField/);
  expect(root.querySelector("[data-group-error]")!.textContent).toMatch(/useFormGroup/);
  expect(root.querySelector("[data-group]")!.textContent).toBe("Paris");
  expect(focusField("address.city", root)).toBe(true);
  (root.querySelector("#save") as HTMLButtonElement).click();
  await nextTick();
  view.unmount();
  expect(email.isConnected).toBe(false);
});

it("binds Vibecn input, textarea, checkbox and switch models", async () => {
  const view = mount(VibecnFields);
  const root = view.element;
  const email = root.querySelector<HTMLInputElement>("#vibe-email")!;
  email.value = "ada@example.com";
  email.dispatchEvent(new Event("input"));
  const bio = root.querySelector<HTMLTextAreaElement>("#vibe-bio")!;
  bio.value = "Hello";
  bio.dispatchEvent(new Event("input"));
  root.querySelector<HTMLInputElement>("#vibe-agree")!.click();
  root.querySelector<HTMLInputElement>("#vibe-notify")!.click();
  await nextTick();
  expect(root.querySelector("[data-email]")!.textContent).toBe("ada@example.com");
  expect(root.querySelector("[data-bio]")!.textContent).toBe("Hello");
  expect(root.querySelector("[data-agree]")!.textContent).toBe("true");
  expect(root.querySelector("[data-notify]")!.textContent).toBe("false");
  view.unmount();
});
